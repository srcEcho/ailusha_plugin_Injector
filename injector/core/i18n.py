CONFIG_PATH = "elsmod_data/config.json"

def load_config(game_dir: str) -> dict:
    path = os.path.join(game_dir, CONFIG_PATH)
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {"lang": "zh", "font_size": 13, "theme": "system"}

def save_config(game_dir: str, config: dict):
    path = os.path.join(game_dir, CONFIG_PATH)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(config, f, ensure_ascii=False, indent=2)

def tr(lang: str, key: str) -> str:
    return STRINGS.get(lang, STRINGS["zh"]).get(key, STRINGS["zh"].get(key, key))
